"""Generate config/school_districts.yaml: Georgia's 180 public school districts (159 county systems and
21 independent city systems), one entry each, keyed to the registry's county/city ids. Websites and
BoardDocs portals are discovered by `gacrawl seed` (state/discovered.json) or set in config/overrides.yaml."""
from __future__ import annotations

import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CITY_SYSTEMS = {  # city system -> county (Georgia's independent city school districts)
    "Atlanta": "Fulton", "Bremen": "Haralson", "Buford": "Gwinnett", "Calhoun": "Gordon", "Carrollton": "Carroll",
    "Cartersville": "Bartow", "Chickamauga": "Walker", "Commerce": "Jackson", "Dalton": "Whitfield", "Decatur": "DeKalb",
    "Dublin": "Laurens", "Gainesville": "Hall", "Jefferson": "Jackson", "Marietta": "Cobb", "Pelham": "Mitchell",
    "Rome": "Floyd", "Social Circle": "Walton", "Thomasville": "Thomas", "Trion": "Chattooga", "Valdosta": "Lowndes",
    "Vidalia": "Toombs",
}


def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def main():
    reg = yaml.safe_load((ROOT / "config" / "jurisdictions.yaml").read_text(encoding="utf-8"))
    munis = {(m["name"], tuple(m.get("counties") or [])): m for m in reg["municipalities"]}
    out = []
    for c in reg["counties"]:
        county = c["name"].removesuffix(" County")
        out.append({"id": f"sd-{slug(county)}", "name": f"{county} County School District", "kind": "school_district",
                    "county": county, "county_id": c["id"], "population": c.get("population"),
                    "aliases": [f"{county} County Schools", f"{county} County School System", f"{county} County Board of Education",
                                f"{county} County Public Schools"]})
    for city, county in CITY_SYSTEMS.items():
        m = next((v for (n, cs), v in munis.items() if n == city and (not cs or county in cs)), None)
        out.append({"id": f"sd-city-{slug(city)}", "name": f"{city} City School District", "kind": "school_district",
                    "county": county, "city": city, "city_id": m["id"] if m else None, "population": (m or {}).get("population"),
                    "aliases": [f"{city} City Schools", f"{city} Public Schools", f"{city} Board of Education", f"{city} City School System"]})
    doc = {"_about": "Every Georgia public school district (159 county systems, 21 city systems). Generated by "
                     "scripts/build_school_districts.py; websites and board portals (BoardDocs) come from `gacrawl seed` "
                     "(state/discovered.json) or config/overrides.yaml.", "districts": out}
    (ROOT / "config" / "school_districts.yaml").write_text(yaml.safe_dump(doc, sort_keys=False, allow_unicode=True), encoding="utf-8")
    print(f"{len(out)} districts")


if __name__ == "__main__":
    main()
